export interface ChapterMeta {
  id: string;
  bookId: string;
  order: number;
  title: string;
  subject: string;
  units: string[];
  pages: [number, number];
  words: number;
  relevant?: boolean;
}

export interface Book {
  id: string;
  std: number;
  title: string;
  source: string;
  chapters: ChapterMeta[];
}

export interface Catalog {
  books: Book[];
}

export interface ChapterContent extends ChapterMeta {
  blocks: { t: 'h' | 'p' | 'li'; text: string; page: number }[];
  summary?: string;
  keyFacts?: string[];
  /** Points to underline; `block` is the index of the block containing `quote` (-1 if not found). */
  highlights?: Highlight[];
}

export interface Highlight {
  text: string;
  kind: 'date' | 'person' | 'place' | 'term' | 'number' | 'event' | 'fact';
  quote: string;
  block: number;
}

